#!/usr/bin/env node
/**
 * Build (and verify) the manual Supabase migration bundle.
 *
 *   node scripts/prepare-migrations.mjs          # rewrite supabase-manual-migration/
 *   node scripts/prepare-migrations.mjs --check  # fail if the bundle has drifted
 *
 * Source of truth: `supabase/migrations/` (the numbered files), `supabase/verify_schema.sql` and
 * `docs/SUPABASE_MIGRATION.md`. The bundle is a copy the owner can hand to the Supabase SQL editor
 * without touching the application repository, plus a manifest that records order and hashes.
 *
 * Nothing here is executed. Migrations are never applied by the app, by CI or by this script.
 */

import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

const CHECK = process.argv.includes("--check");
const ROOT = process.cwd();
const SOURCE_DIR = join(ROOT, "supabase", "migrations");
const VERIFY = join(ROOT, "supabase", "verify_schema.sql");
const GUIDE = join(ROOT, "docs", "SUPABASE_MIGRATION.md");
const OUT = join(ROOT, "supabase-manual-migration");

const sha256 = buffer => createHash("sha256").update(buffer).digest("hex");
const lines = text => text.split(/\r?\n/).length;

function purposeOf(text) {
  const comment = text
    .split(/\r?\n/)
    .map(line => line.trim())
    .find(line => line.startsWith("--"));
  if (!comment) return "No header";
  return comment
    .replace(/^--\s*/, "")
    .replace(/^Shilevi migration \d{4}:\s*/i, "")
    .replace(/\.$/, "");
}

function buildBundle() {
  const files = new Map();

  const migrations = readdirSync(SOURCE_DIR)
    .filter(name => /^\d{4}_.+\.sql$/.test(name))
    .sort();

  if (migrations.length === 0) throw new Error("No migrations found in supabase/migrations.");

  const manifestRows = [];
  for (const [index, name] of migrations.entries()) {
    const text = readFileSync(join(SOURCE_DIR, name), "utf8");
    const destination = `migrations/${name}`;
    files.set(destination, text);
    manifestRows.push({
      position: index + 1,
      file: destination,
      lines: lines(text),
      sha256: sha256(text),
      purpose: purposeOf(text),
    });
  }

  if (!existsSync(VERIFY)) throw new Error("supabase/verify_schema.sql is missing.");
  if (!existsSync(GUIDE)) throw new Error("docs/SUPABASE_MIGRATION.md is missing.");

  const verifyText = readFileSync(VERIFY, "utf8");
  files.set("verify_schema.sql", verifyText);
  files.set("README.md", readFileSync(GUIDE, "utf8"));

  const manifest = [
    "# Manual Supabase migration bundle",
    "",
    "Generated by `scripts/prepare-migrations.mjs` from `supabase/migrations/`. Do not edit files in",
    "this folder: change the migration in the repository, then run `npm run migrations:sync`.",
    "",
    `- Migrations: **${migrations.length}** (0001 → ${migrations[migrations.length - 1].slice(0, 4)})`,
    "- Apply in the order below, in the Supabase SQL editor, one file per run.",
    "- `README.md` is the step-by-step guide (same content as `docs/SUPABASE_MIGRATION.md`).",
    "- `verify_schema.sql` is read-only; run it after the last migration.",
    "",
    "| # | File | Lines | SHA-256 (first 12) | Purpose |",
    "|---|---|---|---|---|",
    ...manifestRows.map(
      row => `| ${row.position} | \`${row.file}\` | ${row.lines} | \`${row.sha256.slice(0, 12)}\` | ${row.purpose} |`,
    ),
    "",
    "## Publication policy",
    "",
    "- SQL schema and policies are not secrets, but this bundle is excluded from `vercel-deploy/`.",
    "- No migration contains credentials. `verify_schema.sql` is read-only.",
    "- Never run these files against a project you are not prepared to upgrade: migrations are",
    "  forward-only, and later migrations assume every earlier one succeeded.",
    "",
  ].join("\n");

  files.set("MANIFEST.md", manifest);
  return { files, manifestRows };
}

const { files, manifestRows } = buildBundle();

if (CHECK) {
  const problems = [];
  if (!existsSync(OUT)) {
    problems.push("supabase-manual-migration/ does not exist — run `npm run migrations:sync`.");
  } else {
    const present = new Set(
      readdirSync(join(OUT, "migrations")).filter(name => name.endsWith(".sql")).map(name => `migrations/${name}`),
    );
    for (const path of files.keys()) {
      if (path.startsWith("migrations/") && !present.has(path)) problems.push(`missing: ${path}`);
      const full = join(OUT, path);
      if (!existsSync(full)) problems.push(`missing: ${path}`);
      else if (sha256(readFileSync(full)) !== sha256(files.get(path))) problems.push(`stale: ${path}`);
    }
    const extra = [...present].filter(path => !files.has(path));
    for (const path of extra) problems.push(`unexpected migration in bundle: ${path}`);
  }

  if (problems.length) {
    console.error(`FAIL — migration bundle is out of sync (${problems.length} problem(s)):`);
    for (const problem of problems) console.error(`  ${problem}`);
    process.exit(1);
  }
  console.log(`PASS — migration bundle matches ${manifestRows.length} migrations, the guide and the verification script.`);
  process.exit(0);
}

rmSync(OUT, { recursive: true, force: true });
mkdirSync(join(OUT, "migrations"), { recursive: true });

for (const [path, content] of files) {
  const destination = join(OUT, path);
  mkdirSync(dirname(destination), { recursive: true });
  writeFileSync(destination, content);
}

console.log(`Wrote supabase-manual-migration/ — ${manifestRows.length} migrations + README.md + verify_schema.sql + MANIFEST.md.`);
console.log(`Latest migration: ${manifestRows[manifestRows.length - 1].file}`);
